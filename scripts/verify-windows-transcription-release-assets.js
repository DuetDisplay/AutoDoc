const { createHash } = require('node:crypto')
const { createReadStream } = require('node:fs')
const { readdir, readFile, stat, writeFile } = require('node:fs/promises')
const path = require('node:path')

const ROOT = process.cwd()
const MANIFEST_PATH = path.join(ROOT, 'resources', 'windows-transcription-manifest.json')

function hashFile(filePath) {
  return new Promise((resolve, reject) => {
    const hash = createHash('sha256')
    const stream = createReadStream(filePath)
    stream.on('data', (chunk) => hash.update(chunk))
    stream.on('error', reject)
    stream.on('end', () => resolve(hash.digest('hex')))
  })
}

function collectUniqueAssets(manifest) {
  const assets = new Map()
  for (const profile of manifest.profiles ?? []) {
    for (const asset of profile.assets ?? []) {
      if (!asset?.filename || assets.has(asset.filename)) continue
      assets.set(asset.filename, asset)
    }
  }
  return assets
}

function uploadFilenames(asset) {
  if (asset.parts?.length) {
    return asset.parts.map((part) => part.filename)
  }
  return [asset.filename]
}

function lookupExpected(asset, filename) {
  if (filename === asset.filename) return asset
  return (asset.parts ?? []).find((part) => part.filename === filename)
}

async function exists(filePath) {
  try {
    await stat(filePath)
    return true
  } catch {
    return false
  }
}

async function main() {
  const assetDir = process.argv[2]
  if (!assetDir) {
    throw new Error('Usage: node scripts/verify-windows-transcription-release-assets.js <assetDir>')
  }

  const committedText = await readFile(MANIFEST_PATH, 'utf8')
  const artifactManifestPath = path.join(assetDir, 'windows-transcription-manifest.json')
  if (
    !(await exists(artifactManifestPath)) ||
    JSON.stringify(JSON.parse(committedText)) !==
      JSON.stringify(JSON.parse(await readFile(artifactManifestPath, 'utf8')))
  ) {
    throw new Error(
      "the committed manifest does not match the one generated by the build run; commit the artifact's copy"
    )
  }

  let firstLine = ''
  try {
    firstLine =
      (await readFile(path.join(assetDir, 'SIGNING-REPORT.md'), 'utf8'))
        .split(/\r?\n/)
        .find((line) => line.trim()) ?? ''
  } catch {
    firstLine = 'DRY RUN'
  }
  if (/DRY RUN/i.test(firstLine)) {
    throw new Error('SIGNING-REPORT.md is missing or its first non-empty line contains DRY RUN')
  }

  const uniqueAssets = collectUniqueAssets(JSON.parse(committedText))
  const uploadFiles = []
  const seen = new Set()
  const mismatches = []

  for (const asset of uniqueAssets.values()) {
    for (const filename of uploadFilenames(asset)) {
      if (seen.has(filename)) continue
      seen.add(filename)
      uploadFiles.push(filename)
      const expected = lookupExpected(asset, filename)
      const filePath = path.join(assetDir, filename)
      if (!(await exists(filePath))) {
        mismatches.push(`${filename}: missing`)
        continue
      }
      const info = await stat(filePath)
      const sha256 = await hashFile(filePath)
      if (info.size !== expected.bytes || sha256 !== expected.sha256) {
        mismatches.push(
          `${filename}: manifest ${expected.bytes} ${expected.sha256} != disk ${info.size} ${sha256}`
        )
      }
    }
  }
  if (mismatches.length) {
    throw new Error(`Asset mismatches:\n${mismatches.map((line) => `  ${line}`).join('\n')}`)
  }

  const extras = (await readdir(assetDir)).filter(
    (name) => /\.zip(\.part\d+)?$/.test(name) && !seen.has(name)
  )
  if (extras.length) {
    throw new Error(`Unexpected zip files in assetDir: ${extras.join(', ')}`)
  }

  await writeFile(path.join(assetDir, 'UPLOAD-FILES.txt'), `${uploadFiles.join('\n')}\n`)
  console.log(`Verified ${uploadFiles.length} upload files`)
}

main().catch((error) => {
  console.error('[verify-windows-transcription-release-assets] Failed')
  console.error(error)
  process.exitCode = 1
})
